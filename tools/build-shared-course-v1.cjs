/* JSON is authoritative; the generated browser bundle avoids async startup races. */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../docs/lab/shared-course');
const read=name=>JSON.parse(fs.readFileSync(path.join(root,name),'utf8'));
const output='/* GENERATED by tools/build-shared-course-v1.cjs; edit JSON sources. */\n'+
 '(function(g){\n'+
 'g.RaceCourseSchemas='+JSON.stringify({blueprint:read('track-blueprint-v1.schema.json'),spec:read('race-course-spec-v1.schema.json')})+';\n'+
 'g.RaceCourseDefinitions='+JSON.stringify({blueprints:[read('kyoto-inner-A.blueprint.json')],specs:[read('kyoto-2000.spec.json')]})+';\n'+
 "})(typeof window==='undefined'?globalThis:window);\n";
const target=path.join(root,'definitions-v1.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==output)throw Error('STALE_COURSE_BUNDLE');}
else fs.writeFileSync(target,output);
